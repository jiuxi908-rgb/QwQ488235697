function dialogueTier(favor){
  const v=favor||0;
  if(v>=95)return 5;
  if(v>=80)return 4;
  if(v>=60)return 3;
  if(v>=40)return 2;
  if(v>=20)return 1;
  return 0;
}
function getDialogueLine(npc,favor){
  const tier=dialogueTier(favor);
  const by=DIALOGUE_BY_TIER[npc.id];
  if(by){
    for(let t=tier;t>=0;t--){
      if(by[t]&&by[t].length)return pickText(by[t]);
    }
  }
  return enrichTalk(npc);
}

