  function lineForAct(npc, act, fav, ctx){
    ctx = ctx||{};
    var t = tier(fav);
    var byNpc = BY_NPC_ACT[npc.id] && BY_NPC_ACT[npc.id][act.id];
    if(byNpc){
      if(act.type==="duel"||act.type==="gamble"){
        var side = ctx.win ? "win" : "lose";
        if(byNpc[side]){
          var s = pickTier(byNpc[side], t);
          if(s) return s;
        }
      }else{
        var s2 = pickTier(byNpc, t);
        if(s2) return s2;
      }
    }
    var byType = BY_TYPE[act.type];
    if(!byType) return"";
    if(act.type==="duel"||act.type==="gamble"){
      var side2 = ctx.win ? "win" : "lose";
      return pickTier(byType[side2], t);
    }
    return pickTier(byType, t);
  }

